    public static List<LanguageOption> Options() => All.Select(l => new LanguageOption(l.Language,
        l.Language == AppLanguage.English ? "English" : $"{l.NativeName} · {l.EnglishName}")).ToList();
}

// Centralized cross-thread-safe lookup used by both the WPF bindings and the
// connection state machine. Every supported language provides its own complete
// dictionary; unknown or missing keys fall back safely to English.
public sealed partial class Localization : INotifyPropertyChanged
{
    public static Localization Instance { get; } = new();
    private AppLanguage _language = AppLanguage.English;
    public AppLanguage Language => _language;
    public bool IsRightToLeft => _language is AppLanguage.Arabic or AppLanguage.Urdu;
    public event PropertyChangedEventHandler? PropertyChanged;

    public string this[string key] => Lookup(key, _language);
    public string Get(string key) => Lookup(key, _language);
    public string Format(string key, params object[] args) =>
        string.Format(CultureInfo.CurrentUICulture, Lookup(key, _language), args);

    public void SetLanguage(AppLanguage language)
    {
        if (!Enum.IsDefined(language)) throw new ArgumentOutOfRangeException(nameof(language));
        _language = language;
        try { CultureInfo.CurrentUICulture = CultureInfo.GetCultureInfo(ToCultureTag(language)); }
        catch (CultureNotFoundException) { }
        CultureInfo.CurrentCulture = CultureInfo.CurrentUICulture;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(string.Empty));
    }

    private static string ToCultureTag(AppLanguage language) => language switch
    {
        AppLanguage.English => "en", AppLanguage.Chinese => "zh-Hans", AppLanguage.Hindi => "hi",
        AppLanguage.Spanish => "es", AppLanguage.French => "fr", AppLanguage.Arabic => "ar",
        AppLanguage.Bengali => "bn", AppLanguage.Russian => "ru", AppLanguage.Portuguese => "pt",
        AppLanguage.Urdu => "ur", AppLanguage.Turkish => "tr", _ => "en"
    };

    internal static IReadOnlyCollection<string> Keys => En.Keys.ToArray();
    internal static bool HasTranslation(AppLanguage language, string key) => Table(language).ContainsKey(key);
    internal static string Raw(AppLanguage language, string key) => Table(language)[key];

    private static IReadOnlyDictionary<string, string> Table(AppLanguage language) => language switch
    {
        AppLanguage.Chinese => Zh,
        AppLanguage.Hindi => Hi,
        AppLanguage.Spanish => Es,
        AppLanguage.French => Fr,
        AppLanguage.Arabic => Ar,
        AppLanguage.Bengali => Bn,
        AppLanguage.Russian => Ru,
        AppLanguage.Portuguese => Pt,
        AppLanguage.Urdu => Ur,
        AppLanguage.Turkish => Tr,
        _ => En
    };

    private static string Lookup(string key, AppLanguage language) =>
        Table(language).TryGetValue(key, out var translated) ? translated
        : En.TryGetValue(key, out var english) ? english : key;

