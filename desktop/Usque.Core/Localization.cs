// The ten most spoken languages in the world (by total speakers) plus Turkish.
public enum AppLanguage { English, Chinese, Hindi, Spanish, French, Arabic, Bengali, Russian, Portuguese, Urdu, Turkish }

public sealed record LanguageInfo(AppLanguage Language, string NativeName, string EnglishName);
public sealed record LanguageOption(AppLanguage Language, string Display);

public static class Languages
{
    public static readonly LanguageInfo[] All =
    [
        new(AppLanguage.English, "English", "English"),
        new(AppLanguage.Chinese, "中文", "Chinese (Mandarin)"),
        new(AppLanguage.Hindi, "हिन्दी", "Hindi"),
        new(AppLanguage.Spanish, "Español", "Spanish"),
        new(AppLanguage.French, "Français", "French"),
        new(AppLanguage.Arabic, "العربية", "Arabic"),
        new(AppLanguage.Bengali, "বাংলা", "Bengali"),
        new(AppLanguage.Russian, "Русский", "Russian"),
        new(AppLanguage.Portuguese, "Português", "Portuguese"),
        new(AppLanguage.Urdu, "اردو", "Urdu"),
        new(AppLanguage.Turkish, "Türkçe", "Turkish")
